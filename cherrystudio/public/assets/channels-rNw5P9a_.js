function getChannelSummary(channel) {
	const cfg = channel.config;
	const chatIds = cfg.allowed_chat_ids ?? [];
	const parts = [];
	switch (channel.type) {
		case "feishu": {
			if (cfg.app_id) parts.push(truncateId(cfg.app_id));
			const domain = cfg.domain;
			parts.push(domain === "lark" ? "Lark (International)" : "Feishu (China)");
			break;
		}
		case "telegram":
			if (cfg.bot_token) parts.push(`Token: ${truncateId(cfg.bot_token)}`);
			if (chatIds.length > 0) parts.push(`${chatIds.length} chat IDs`);
			break;
		case "qq":
			if (cfg.app_id) parts.push(truncateId(cfg.app_id));
			if (chatIds.length > 0) parts.push(`${chatIds.length} chat IDs`);
			break;
		case "discord": {
			if (cfg.bot_token) parts.push(`Token: ${truncateId(cfg.bot_token)}`);
			const channelIds = cfg.allowed_channel_ids ?? [];
			if (channelIds.length > 0) parts.push(`${channelIds.length} channel IDs`);
			break;
		}
		case "slack": {
			if (cfg.bot_token) parts.push(`Token: ${truncateId(cfg.bot_token)}`);
			const slackChannelIds = cfg.allowed_channel_ids ?? [];
			if (slackChannelIds.length > 0) parts.push(`${slackChannelIds.length} channel IDs`);
			break;
		}
		case "wechat": break;
	}
	return parts.join(" · ");
}
